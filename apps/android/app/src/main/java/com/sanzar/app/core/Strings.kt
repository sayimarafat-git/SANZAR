        table[lang]?.get(key) ?: table["en"]?.get(key) ?: key

    operator fun invoke(key: String, args: Map<String, Any> = emptyMap()): String {
        var s = t(key)
        args.forEach { (k, v) -> s = s.replace("{$k}", v.toString()) }
        return s
    }

    fun timeAgo(epochMillis: Long): String {
        val diffSec = ((System.currentTimeMillis() - epochMillis).coerceAtLeast(0L)) / 1000L
        return when {
            diffSec < 60L -> invoke("justNow")
            diffSec < 3600L -> invoke("minAgo", mapOf("n" to (diffSec / 60L)))
            diffSec < 86400L -> invoke("hAgo", mapOf("n" to (diffSec / 3600L)))
            else -> invoke("dAgo", mapOf("n" to (diffSec / 86400L)))
        }
    }

