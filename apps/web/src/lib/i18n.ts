export function translate(lang: Lang, key: string, args?: Record<string, string | number>): string {
  let s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (args) {
    for (const [k, v] of Object.entries(args)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function localizedName(
  item: { name_en?: string; name_bn?: string; name_zh?: string } | undefined | null,
  lang: Lang,
  fallback = ''
): string {
  if (!item) return fallback;
  const pick = lang === 'bn' ? item.name_bn : lang === 'zh' ? item.name_zh : item.name_en;
  return (pick && pick.trim()) || item.name_en || fallback;
}
