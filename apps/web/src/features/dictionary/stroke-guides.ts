interface GraphemeSegLike {
  segment(input: string): Iterable<{ segment: string }>;
}

/** Splits Bangla or English text into proper visual grapheme clusters (never breaks হ্যা or ক্ষ). */
export function splitIntoGraphemeClusters(word: string, lang: 'bn' | 'en'): string[] {
  const clean = word.trim();
  if (!clean) return [];
  const IntlSeg = typeof Intl !== 'undefined'
    ? (Intl as unknown as { Segmenter?: new (l: string, o: { granularity: string }) => GraphemeSegLike })
    : null;

  let rawClusters: string[];
  if (IntlSeg?.Segmenter) {
    const seg = new IntlSeg.Segmenter(lang === 'bn' ? 'bn' : 'en', { granularity: 'grapheme' });
    rawClusters = Array.from(seg.segment(clean), (x) => x.segment);
  } else {
    // Fallback regex grouping Bangla base + virama/consonant conjuncts + dependent vowel signs
    rawClusters =
      lang === 'bn'
        ? clean.match(/[\u0980-\u09ff](?:\u09cd[\u0980-\u09ff]|[\u0981-\u0983\u09bc\u09be-\u09cc\u09d7])*/g) || []
        : Array.from(clean);
  }

  return rawClusters
    .filter((c) => (lang === 'bn' ? /[\u0980-\u09ff]/.test(c) : /[a-zA-Z]/.test(c)))
    .slice(0, 16);
}

export interface BanglaConstituent {
  symbol: string;
  label: string;
  isBaseLetter: boolean;
}

/** Breaks a Bangla grapheme cluster (e.g. "হ্যা" or "ক্ষ") into its constituent codepoints & labels. */
export function decomposeBanglaCluster(cluster: string): BanglaConstituent[] {
  const codepoints = Array.from(cluster);
  if (codepoints.length <= 1) return [];
  return codepoints.map((ch) => {
    const kar = BANGLA_KAR_NAMES[ch];
    if (kar) {
      return { symbol: ch === '্' ? '্' : `◌${ch}`, label: kar, isBaseLetter: false };
    }
    const cp = ch.codePointAt(0) || 0;
    const isBase = (cp >= 0x0985 && cp <= 0x09b9) || cp === 0x09ce || (cp >= 0x09dc && cp <= 0x09df);
    return { symbol: ch, label: ch, isBaseLetter: isBase };
  });
}
