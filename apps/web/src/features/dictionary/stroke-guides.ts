/** Bangla Matra (headline) classification for authentic Bengali handwriting pedagogy. */
const HALF_MATRA = new Set(['খ', 'গ', 'ণ', 'থ', 'ধ', 'প', 'শ', 'ঋ']);
const NO_MATRA = new Set(['এ', 'ঐ', 'ও', 'ঔ', 'ঙ', 'ঞ', 'ৎ', 'ং', 'ঃ', 'ঁ']);

export type MatraType = 'full' | 'half' | 'none';

export function getBanglaMatraInfo(cluster: string): { type: MatraType; label: string; bnLabel: string } {
  const base = Array.from(cluster).find((ch) => {
    const cp = ch.codePointAt(0) || 0;
    return (cp >= 0x0985 && cp <= 0x09b9) || cp === 0x09ce || (cp >= 0x09dc && cp <= 0x09df);
  });
  if (!base) return { type: 'full', label: 'Matra line', bnLabel: 'মাত্রা' };
  if (NO_MATRA.has(base)) return { type: 'none', label: 'No Matra', bnLabel: 'মাত্রাহীন' };
  if (HALF_MATRA.has(base)) return { type: 'half', label: 'Half Matra', bnLabel: 'অর্ধমাত্রা' };
  return { type: 'full', label: 'Full Matra', bnLabel: 'পূর্ণমাত্রা' };
}

